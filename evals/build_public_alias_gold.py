"""Build the *public* alias gold set from a private real-text gold set.

Why this exists
---------------
`build_alias_gold.py` grows a gold set from a real Reddit dump. Real posts are
third-party content and can carry personal data, so that file must never be
committed. What *is* safe — and what the alias matcher is actually tested on — is
the **surface form** a school is referred to by in the wild ("UB", "Pitt",
"Stony Brook university"). School names are facts, not user expression.

This script keeps the real-world surface-form distribution and discards the prose:

1. read the private real-text gold (git-ignored `evals/gold/private/`),
2. recover which alias surface form triggered each label,
3. drop labels that point at non-schools (spreadsheet aggregate rows, GAP-056)
   and surface forms that are ordinary English words or ambiguous initialisms,
4. re-emit each surviving (canonical_id, surface form) inside a hand-written,
   fully synthetic carrier sentence; negatives are hand-written as well.

Hand-written entries already in the public file (traps, short forms, no-match
cases) are preserved verbatim.

Run: `python -m evals.build_public_alias_gold [--private PATH] [--sqlite PATH] [--out PATH]`
"""

