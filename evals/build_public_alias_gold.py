def _load_aliases(sqlite_path: Path) -> dict[str, set[str]]:
    conn = sqlite3.connect(sqlite_path)
    try:
        rows = conn.execute("SELECT canonical_id, alias_text FROM alias").fetchall()
    finally:
        conn.close()
    out: dict[str, set[str]] = defaultdict(set)
    for canonical_id, alias_text in rows:
        out[str(canonical_id)].add(str(alias_text))
    return out


def _read_gold(path: Path) -> list[dict[str, object]]:
    out: list[dict[str, object]] = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line and not line.startswith("#"):
            out.append(json.loads(line))
    return out


def _surface_form(text: str, aliases: set[str]) -> str | None:
    """Return the alias surface form exactly as it was typed in `text`."""

    for alias in sorted(aliases, key=len, reverse=True):
        if len(alias) < 2:
            continue
        pattern = rf"\b{re.escape(alias)}\b" if len(alias) <= 5 else re.escape(alias)
        match = re.search(pattern, text, re.IGNORECASE)
        if match:
            return match.group(0)
    return None


def _is_school(canonical_id: str) -> bool:
    return not any(marker in canonical_id for marker in _NON_SCHOOL_MARKERS)


def build(*, private_path: Path, sqlite_path: Path, out_path: Path, seed: int) -> tuple[int, int, int]:
    aliases = _load_aliases(sqlite_path)
    entries = _read_gold(private_path)

    hand_written = [e for e in entries if _REAL_MARKER not in str(e.get("note", ""))]
    real_positives = [
        e for e in entries
        if _REAL_MARKER in str(e.get("note", "")) and e.get("expected_canonical_id")
    ]

    rng = random.Random(seed)
    carriers = list(_CARRIERS)
    positives: list[dict[str, object]] = []
    for entry in real_positives:
        canonical_id = str(entry["expected_canonical_id"])
        if not _is_school(canonical_id):
            continue
        form = _surface_form(str(entry["text"]), aliases.get(canonical_id, set()))
        if form is None or form.lower() in _AMBIGUOUS_FORMS:
            continue
        positives.append({
            "text": rng.choice(carriers).format(alias=form),
            "expected_canonical_id": canonical_id,
            "note": _SYNTH_NOTE,
        })

    negatives: list[dict[str, object]] = [
        {"text": text, "expected_canonical_id": None, "note": _SYNTH_NEG_NOTE}
        for text in _NEGATIVES
    ]

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(_HEADER)
        for entry in hand_written + positives + negatives:
            fh.write(json.dumps(entry, ensure_ascii=False) + "\n")
    return len(hand_written), len(positives), len(negatives)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--private", type=Path, default=_DEFAULT_PRIVATE)
    parser.add_argument("--sqlite", type=Path, default=_DEFAULT_SQLITE)
    parser.add_argument("--out", type=Path, default=_DEFAULT_PUBLIC)
    parser.add_argument("--seed", type=int, default=20260521)
    args = parser.parse_args(argv)

    for label, path in (("private gold", args.private), ("SQLite alias DB", args.sqlite)):
        if not path.is_file():
            print(f"[err] {label} not found: {path}", file=sys.stderr)
            return 2

    kept, pos, neg = build(
        private_path=args.private, sqlite_path=args.sqlite, out_path=args.out, seed=args.seed,
    )
    print(f"hand-written kept: {kept}")
    print(f"synthetic positives: {pos}")
    print(f"synthetic negatives: {neg}")
    print(f"wrote {kept + pos + neg} entries -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
